function patch(file, nav, blocks) {
  const p = path.join(root, "messages", file);
  const data = JSON.parse(fs.readFileSync(p, "utf8"));
  Object.assign(data.nav, nav);
  for (const [key, value] of Object.entries(blocks)) data[key] = value;
  fs.writeFileSync(p, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log("actualizat", file, "-", Object.keys(blocks).length, "blocuri noi");
}

